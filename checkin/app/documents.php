/** Каноничный текст документа — от него считается SHA-256 версии, показанной гостю. */
function document_canonical_text(array $doc): string
{
    $out = [$doc['title'], '№ ' . $doc['number'], 'Версия: ' . $doc['version']];
    foreach ($doc['contract'] as $s) {
        $out[] = $s['title'];
        array_push($out, ...$s['points']);
    }
    if ($doc['inventory']) {
        $out[] = 'Приложение № 1. Опись имущества';
        foreach ($doc['inventory'] as $g) {
            $out[] = $g['group'];
            foreach ($g['items'] as $i) $out[] = $i['name'] . ' | ' . $i['qty'] . ' | ' . inventory_value($i['value']);
        }
        foreach ($doc['defects'] as $d) $out[] = 'Дефект: ' . $d;
    }
    if ($doc['rules']) {
        $out[] = 'Приложение № 2. Правила безопасности фермы';
        foreach ($doc['rules'] as $r) $out[] = $r['title'] . ': ' . $r['text'];
    }
    if ($doc['consent']) {
        $out[] = $doc['consent']['title'];
        array_push($out, ...$doc['consent']['points']);
    }
    return implode("\n", $out);
}

function inventory_value(?int $v): string
{
    return $v === null ? 'по фактической стоимости восстановления' : fmt_rub($v);
}

